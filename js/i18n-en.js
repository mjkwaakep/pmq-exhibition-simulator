/** root 아래 글자 노드 중 사전에 있는 문구를 영어로 바꾼다(앞뒤 공백은 유지). */
export function translateToEnglish(root = document.body) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (EN[text]) node.nodeValue = node.nodeValue.replace(text, EN[text]);
  }
  document.documentElement.lang = 'en';
  document.title = 'PMQ Poster Wall Simulator · View only';
}
